-- ============================================================================
--  northwind_dwh — схема «звезда»
--  Факт: fact_order_line (одна строка = позиция заказа)
--  Измерения плоские: дата, клиент, товар, сотрудник, перевозчик.
--  Страна и город лежат в dim_customer, категория и поставщик — в dim_product.
--  Отдельных таблиц-иерархий нет: это и отличает звезду от снежинки.
--  Скрипт идемпотентен.
-- ============================================================================

DROP TABLE IF EXISTS fact_order_line CASCADE;
DROP TABLE IF EXISTS dim_customer    CASCADE;
DROP TABLE IF EXISTS dim_product     CASCADE;
DROP TABLE IF EXISTS dim_employee    CASCADE;
DROP TABLE IF EXISTS dim_shipper     CASCADE;
DROP TABLE IF EXISTS dim_date        CASCADE;

CREATE TABLE dim_date (
    date_key   integer  PRIMARY KEY,          -- YYYYMMDD
    full_date  date     NOT NULL UNIQUE,
    day        smallint NOT NULL,
    month      smallint NOT NULL,
    month_name text     NOT NULL,
    quarter    smallint NOT NULL,
    year       smallint NOT NULL
);

-- Клиент вместе с географией (атрибуты, не отдельные измерения)
CREATE TABLE dim_customer (
    customer_key integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id  varchar(5) NOT NULL UNIQUE,
    company_name text       NOT NULL,
    contact_name text,
    city         text       NOT NULL,
    region       text       NOT NULL,         -- «Не указан», если в источнике NULL
    country      text       NOT NULL
);

-- Товар вместе с категорией и поставщиком
CREATE TABLE dim_product (
    product_key      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id       smallint NOT NULL UNIQUE,
    product_name     text     NOT NULL,
    category_name    text     NOT NULL,
    supplier_name    text     NOT NULL,
    supplier_country text     NOT NULL,
    quantity_per_unit text,
    discontinued     boolean  NOT NULL
);

CREATE TABLE dim_employee (
    employee_key integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id  smallint NOT NULL UNIQUE,
    full_name    text     NOT NULL,
    title        text,
    city         text     NOT NULL,
    country      text     NOT NULL,
    manager_name text                          -- денормализованное имя руководителя
);

CREATE TABLE dim_shipper (
    shipper_key  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shipper_id   smallint NOT NULL UNIQUE,
    company_name text     NOT NULL
);

-- order_id — вырожденное измерение (номер заказа без своей таблицы).
-- order_freight повторён на каждой строке заказа: суммировать его напрямую нельзя,
-- сначала нужно свернуть строки до заказа.
CREATE TABLE fact_order_line (
    order_line_key  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id        smallint      NOT NULL,
    date_key        integer       NOT NULL REFERENCES dim_date (date_key),
    customer_key    integer       NOT NULL REFERENCES dim_customer (customer_key),
    product_key     integer       NOT NULL REFERENCES dim_product (product_key),
    employee_key    integer       NOT NULL REFERENCES dim_employee (employee_key),
    shipper_key     integer       NOT NULL REFERENCES dim_shipper (shipper_key),
    quantity        integer       NOT NULL,
    unit_price      numeric(12,2) NOT NULL,
    discount        numeric(6,4)  NOT NULL,
    line_total      numeric(14,2) NOT NULL,
    discount_amount numeric(14,2) NOT NULL,
    order_freight   numeric(12,2) NOT NULL
);

CREATE INDEX fact_order_line_date_idx     ON fact_order_line (date_key);
CREATE INDEX fact_order_line_customer_idx ON fact_order_line (customer_key);
CREATE INDEX fact_order_line_product_idx  ON fact_order_line (product_key);
CREATE INDEX fact_order_line_employee_idx ON fact_order_line (employee_key);
CREATE INDEX fact_order_line_shipper_idx  ON fact_order_line (shipper_key);
CREATE INDEX fact_order_line_order_idx    ON fact_order_line (order_id);
